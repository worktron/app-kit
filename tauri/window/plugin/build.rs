// The Settings window's commands (src/settings.rs), from which Tauri makes the permissions `allow-<command>` that
// only that window is granted. permissions/default.toml grants none of them. ../names.ts holds the same names, and
// test/tauri-window.test.ts holds them to these.
const COMMANDS: &[&str] = &["open_at_login_status", "open_at_login_set", "open_login_items"];

fn main() {
    tauri_plugin::Builder::new(COMMANDS).build();
    // Every app-kit checkout shares one build folder (scripts/gates.sh), so Cargo can judge this script up to date from
    // a run in another checkout and never write this checkout's generated permission files, which the tests read
    // (src/test_support.rs). A path that does not exist makes Cargo run the script again, so a checkout without them
    // gets them on its first build, and once they are written it stays up to date.
    println!("cargo:rerun-if-changed=permissions/autogenerated/commands");
}
