// The check before an iPhone build that Tauri's deep-link plugin would not erase the app's sign-in domain, and the
// version comparison it shares with the TestFlight upload's Tauri CLI check, on made-up checkouts.
import { afterEach, beforeEach, describe, expect, test } from 'bun:test';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { associatedDomains, deepLinkProblem, entitlementsFile, erases, lockedDeepLink } from '../tauri/deep-link-entitlements.ts';
import { belowFloor, readVersion } from '../tauri/version.ts';
import { scratch } from './testflight-stand-in.ts';

/** A Cargo.lock as cargo writes it, with the deep-link plugin at `version` among other packages. */
function cargoLock(version: string | null): string {
  const deepLink = version ? `\n[[package]]\nname = "tauri-plugin-deep-link"\nversion = "${version}"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n` : '';
  return `# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "tauri"\nversion = "2.12.5"\n${deepLink}\n[[package]]\nname = "tauri-plugin-deep-link-extra"\nversion = "1.0.0"\n`;
}

/** An iPhone entitlements plist as Xcode writes it, with push and these associated domains. */
function entitlements(domains: string[] | null): string {
  const list = domains ? `\t<key>com.apple.developer.associated-domains</key>\n\t<array>\n${domains.map((d) => `\t\t<string>${d}</string>`).join('\n')}\n\t</array>\n` : '';
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0">\n<dict>\n\t<key>aps-environment</key>\n\t<string>development</string>\n${list}</dict>\n</plist>\n`;
}

describe('the versions', () => {
  test('a version is read with its pre-release, and anything else is not a version', () => {
    expect(readVersion('2.6.3')).toEqual({ parts: [2, 6, 3], preRelease: false });
    expect(readVersion('3.0.0-alpha.3')).toEqual({ parts: [3, 0, 0], preRelease: true });
    expect(readVersion('2.12.1+build.5')).toEqual({ parts: [2, 12, 1], preRelease: false });
    expect(readVersion('2.6')).toBeNull();
    expect(readVersion('')).toBeNull();
  });

  test('below the floor: an older number, a pre-release of the floor itself, and anything unreadable', () => {
    expect(belowFloor('2.12.0', [2, 12, 1])).toBe(true);
    expect(belowFloor('2.12.1-rc.1', [2, 12, 1])).toBe(true);
    expect(belowFloor('2.12.1', [2, 12, 1])).toBe(false);
    expect(belowFloor('2.13.0-alpha.1', [2, 12, 1])).toBe(false);
    expect(belowFloor('3.0.0', [2, 12, 1])).toBe(false);
    expect(belowFloor('not a version', [2, 12, 1])).toBe(true);
  });

  test('the deep-link plugins that erase: before 2.6.3, and the 3.0.0 pre-releases, which never took the fix', () => {
    for (const version of ['2.5.0', '2.6.1', '2.6.2', '3.0.0-alpha.0', '3.0.0-alpha.3']) expect(erases(version)).toBe(true);
    for (const version of ['2.6.3', '2.7.0']) expect(erases(version)).toBe(false);
  });
});

describe('what the files say', () => {
  test("the plugin's versions in a Cargo.lock, and no other package's", () => {
    expect(lockedDeepLink(cargoLock('2.5.0'))).toEqual(['2.5.0']);
    expect(lockedDeepLink(cargoLock(null))).toEqual([]);
  });

  test("an entitlements file's associated domains", () => {
    expect(associatedDomains(entitlements(['webcredentials:app.example.com', 'applinks:app.example.com']))).toEqual(['webcredentials:app.example.com', 'applinks:app.example.com']);
    expect(associatedDomains(entitlements(null))).toEqual([]);
  });
});

describe('the check before a build', () => {
  let place: ReturnType<typeof scratch>;
  let app: string;
  const project = 'sample-shell';
  const write = (files: Record<string, string>) => {
    for (const [path, text] of Object.entries(files)) {
      mkdirSync(join(app, path, '..'), { recursive: true });
      writeFileSync(join(app, path), text);
    }
  };

  beforeEach(() => {
    place = scratch('deep-link-');
    app = place.folder;
  });
  afterEach(() => place.done());

  test('an erasing plugin with a sign-in domain is refused, naming the version, the entry and the update', () => {
    write({ 'src-tauri/Cargo.lock': cargoLock('2.5.0'), [entitlementsFile(project)]: entitlements(['webcredentials:app.example.com']) });
    expect(deepLinkProblem(app, project)).toBe(
      'src-tauri/Cargo.lock locks tauri-plugin-deep-link 2.5.0, whose build script deletes webcredentials:app.example.com from src-tauri/gen/apple/sample-shell_iOS/sample-shell_iOS.entitlements on a first iPhone build, so the app loses it once that file is committed. Run cargo update -p tauri-plugin-deep-link in src-tauri (2.6.3 or later keeps it), run one iPhone build, and commit Cargo.lock with the Info.plist change it makes.',
    );
  });

  test("a Cargo.lock at the checkout's root, as a workspace keeps it, is read too", () => {
    write({ 'Cargo.lock': cargoLock('3.0.0-alpha.3'), [entitlementsFile(project)]: entitlements(['webcredentials:app.example.com']) });
    expect(deepLinkProblem(app, project)).toStartWith('Cargo.lock locks tauri-plugin-deep-link 3.0.0-alpha.3,');
  });

  test('a plugin that keeps the entry, an erasing one with only its own applinks or no domains, and no plugin at all pass', () => {
    write({ 'src-tauri/Cargo.lock': cargoLock('2.6.3'), [entitlementsFile(project)]: entitlements(['webcredentials:app.example.com']) });
    expect(deepLinkProblem(app, project)).toBeNull();
    write({ 'src-tauri/Cargo.lock': cargoLock('2.5.0'), [entitlementsFile(project)]: entitlements(['applinks:app.example.com']) });
    expect(deepLinkProblem(app, project)).toBeNull();
    write({ [entitlementsFile(project)]: entitlements(null) });
    expect(deepLinkProblem(app, project)).toBeNull();
    write({ 'src-tauri/Cargo.lock': cargoLock(null), [entitlementsFile(project)]: entitlements(['webcredentials:app.example.com']) });
    expect(deepLinkProblem(app, project)).toBeNull();
  });

  test('a checkout with no Cargo.lock or no entitlements file passes', () => {
    write({ [entitlementsFile(project)]: entitlements(['webcredentials:app.example.com']) });
    expect(deepLinkProblem(app, project)).toBeNull();
    expect(deepLinkProblem(app, 'another-project')).toBeNull();
  });
});
